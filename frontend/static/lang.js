var currentLang = localStorage.getItem('krishiLang') || 'en';

function t(key) {
  return translations[currentLang][key] || translations['en'][key] || key;
}

function applyLanguage() {
  // Normal text elements
  document.querySelectorAll('[data-lang]').forEach(function(el) {
    var key = el.getAttribute('data-lang');
    el.textContent = t(key);
  });
  // Placeholder attributes
  document.querySelectorAll('[data-lang-placeholder]').forEach(function(el) {
    var key = el.getAttribute('data-lang-placeholder');
    el.placeholder = t(key);
  });
  // Select <option> elements
  document.querySelectorAll('option[data-lang]').forEach(function(el) {
    var key = el.getAttribute('data-lang');
    el.textContent = t(key);
  });

  // Update toggle button text
  var btn = document.getElementById('langToggleBtn');
  if (btn) btn.textContent = currentLang === 'en' ? '🇮🇳 हिंदी' : '🇬🇧 English';

  // Update html lang attribute
  document.documentElement.lang = currentLang;
}

function toggleLanguage() {
  currentLang = currentLang === 'en' ? 'hi' : 'en';
  localStorage.setItem('krishiLang', currentLang);
  applyLanguage();
}

document.addEventListener('DOMContentLoaded', function() {
  applyLanguage();
});